// Fisher–Yates sampling without replacement. This is decorative randomness,
// not a security token; no cookies, storage, or remote requests are needed.
export const pickClosingBooks = (random: () => number = Math.random) => {
  const count = random() < 0.5 ? 5 : 6
  const shuffled = [...bookCoverPool]
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1))
    ;[shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]]
  }
  return shuffled.slice(0, count)
}
